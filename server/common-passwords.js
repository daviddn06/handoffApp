/** Fold the obvious substitutions so P@ssw0rd reads as password. */
export function normalizePassword(value) {
  return String(value)
    .toLowerCase()
    .replace(/[@4]/g, "a")
    .replace(/[$5]/g, "s")
    .replace(/[0]/g, "o")
    .replace(/[1!|]/g, "i")
    .replace(/[3]/g, "e")
    .replace(/[7]/g, "t")
    .replace(/[+]/g, "t");
}

/** True when the password is one of the first guesses an attacker makes. */
export function isCommonPassword(value) {
  const raw = String(value).toLowerCase();
  const bases = [
    raw,
    // Trojans2026 and P@ssw0rd! are the same guess with decoration on.
    raw.replace(/^[\d\W_]+/, "").replace(/[\d\W_]+$/, ""),
    raw.replace(/[^a-z0-9]+/g, ""),
    raw.replace(/[^a-z]+/g, ""),
  ];
  for (const base of bases) {
    if (!base) continue;
    if (COMMON_PASSWORDS.has(base)) return true;
    const folded = normalizePassword(base);
    if (COMMON_PASSWORDS.has(folded)) return true;
    if (COMMON_PASSWORDS.has(folded.replace(/[^a-z]+/g, ""))) return true;
  }
  return false;
}
